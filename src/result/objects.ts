// Detail views for any object in the capture (used by the inspector drawer and Resources tab).

import { refId, type Ctx } from './ctx';
import { attachmentsTable, bindGroupCard, pipelineStages, pipelineView } from './details';
import { fmtBytes, h, kv, section, type Child } from './dom';
import { shortType } from './model';
import { codeView } from './modals';
import { imageBox, later, loadBufferSnapshot, ptree, rawViewer, refLink, samplerSummary, texSummary, usageText } from './widgets';

export function objectTitle(o: any): string
{
  if (!o) return 'Unknown object';
  return `${shortType(o.type)}${o.label ? ` "${o.label}"` : ''} #${o.id}`;
}

export function renderObject(ctx: Ctx, id: number): HTMLElement
{
  const o = ctx.cap.objects[id];
  const el = h('div', { class: 'details', style: 'padding:0' });
  if (!o)
  {
    el.append(h('div', { class: 'empty-state' }, `Object #${id} is not part of this capture.`));
    return el;
  }
  el.append(h('h2', null, objectTitle(o)));
  el.append(h('div', { class: 'subtitle' }, o.type));

  switch (o.type)
  {
    case 'GPUTexture': textureView(ctx, o, el); break;
    case 'GPUTextureView': viewView(ctx, o, el); break;
    case 'GPUBuffer': bufferView(ctx, o, el); break;
    case 'GPUSampler':
      el.append(kv([['Summary', samplerSummary(o.desc)]]), section('Descriptor', () => ptree(ctx, o.desc), { key: 'o-desc' }));
      break;
    case 'GPUShaderModule':
      shaderModuleView(ctx, o, el);
      break;
    case 'GPURenderPipeline':
    case 'GPUComputePipeline':
    {
      const stages = pipelineStages(o);
      el.append(h('div', { style: 'display:flex;gap:6px;margin-bottom:8px' }, stages.map((s, i) => h('button', { class: 'btn small', on: { click: () => ctx.openShader(stages, i) } }, `${s.stage} shader`))));
      el.append(pipelineView(ctx, o, stages));
      el.append(section('Descriptor', () => ptree(ctx, o.desc), { key: 'o-desc', collapsed: true }));
      usedBy(ctx, id, el);
      break;
    }
    case 'GPUBindGroup':
      el.append(kv([['Layout', o.desc?.layout ? refLink(ctx, o.desc.layout) : '']]));
      el.append(bindGroupCard(ctx, null, { index: -1, bindGroup: { $ref: id }, offsets: [] }, []));
      el.append(h('div', { class: 'note' }, 'Select a draw that uses this bind group to see its buffer contents and texture previews as that pass saw them.'));
      usedBy(ctx, id, el);
      break;
    case 'GPUBindGroupLayout':
      if (o.auto) el.append(kv([['Generated by', refLink(ctx, o.auto)], ['Group', String(o.group)]]));
      else el.append(bglTable(ctx, o.desc));
      break;
    case 'GPUPipelineLayout':
      el.append(kv((o.desc?.bindGroupLayouts ?? []).map((r: any, i: number): [string, Child] => [`group ${i}`, r ? refLink(ctx, r) : 'empty'])));
      break;
    case 'GPURenderBundle':
      el.append(kv([['Draws', String(o.draws)], ['Commands', String(o.cmds?.length ?? 0)]]), section('Encoder descriptor', () => ptree(ctx, o.encoderDesc), { key: 'o-bdesc' }));
      break;
    case 'GPUAdapter':
    case 'GPUDevice':
      deviceView(ctx, o, el);
      break;
    case 'GPUCanvasContext':
      el.append(kv([['Canvas', o.canvas ? `${o.canvas.tag} ${o.canvas.id ? `#${o.canvas.id}` : ''} ${o.canvas.width}×${o.canvas.height}` : '']]), section('Configuration', () => ptree(ctx, o.config), { key: 'o-cfg' }));
      break;
    default:
      el.append(ptree(ctx, o));
  }
  return el;
}

function bglTable(ctx: Ctx, desc: any): HTMLElement
{
  const entries: any[] = desc?.entries ?? [];
  return h('table', { class: 'grid' },
    h('tr', null, h('th', null, 'Binding'), h('th', null, 'Visibility'), h('th', null, 'Type')),
    entries.map((e) =>
    {
      const kind = e.buffer ? 'buffer' : e.sampler ? 'sampler' : e.texture ? 'texture' : e.storageTexture ? 'storageTexture' : e.externalTexture ? 'externalTexture' : '?';
      return h('tr', null, h('td', null, String(e.binding)), h('td', { class: 'mono' }, usageText('stage', e.visibility)), h('td', null, h('span', { class: 'mono' }, kind, ' '), ptree(ctx, e[kind] ?? {})));
    }));
}

function textureView(ctx: Ctx, o: any, el: HTMLElement): void
{
  el.append(kv([
    ['Summary', texSummary(o)],
    ['Format', o.format],
    ['Size', `${o.width} × ${o.height} × ${o.depthOrArrayLayers}`],
    ['Dimension', o.dimension],
    ['Mip levels', String(o.mipLevelCount)],
    ['Samples', String(o.sampleCount)],
    ['Usage', usageText('texture', o.usage)],
    ['View formats', o.viewFormats ? o.viewFormats.join(', ') : ''],
    ['Canvas', o.canvasContext ? refLink(ctx, o.canvasContext) : ''],
    ['Destroyed', o.destroyed ? 'yes' : '']
  ]));
  const snaps = Object.entries(ctx.cap.snapshots).filter(([, s]) => s.texture === o.id).map(([k]) => Number(k)).sort((a, b) => a - b);
  if (snaps.length)
  {
    el.append(section(`Images in this capture (${snaps.length})`, () => h('div', { class: 'images' }, snaps.slice(0, 120).map((sid) =>
    {
      const uses = ctx.snapUses(sid);
      const first = uses[0];
      const cap: Child = first
        ? h('a', { href: '#', on: { click: (e: Event) => { e.preventDefault(); ctx.showTab('commands'); ctx.selectNode(first.node, true); } } }, `${first.role} · ${first.node.drawNo ? `#${first.node.drawNo}` : first.node.label}`)
        : '';
      return imageBox(ctx, sid, { size: 'small', caption: cap });
    })), { key: 'o-snaps' }));
  }
  else
  {
    el.append(h('div', { class: 'note' }, 'No image of this texture was taken in this capture.'));
  }
}

function viewView(ctx: Ctx, o: any, el: HTMLElement): void
{
  el.append(kv([['Texture', o.texture ? refLink(ctx, o.texture) : '']]));
  if (o.resolved) el.append(section('Resolved view', () => ptree(ctx, o.resolved), { key: 'o-res' }));
  el.append(section('Descriptor', () => ptree(ctx, o.desc), { key: 'o-desc', collapsed: true }));
}

function bufferView(ctx: Ctx, o: any, el: HTMLElement): void
{
  el.append(kv([
    ['Size', `${o.size} (${fmtBytes(o.size)})`],
    ['Usage', usageText('buffer', o.usage)],
    ['Map state', o.mapState],
    ['Destroyed', o.destroyed ? 'yes' : '']
  ]));
  const snaps = Object.entries(ctx.cap.bufferSnapshots).filter(([, s]) => s.buffer === o.id);
  if (!snaps.length)
  {
    el.append(h('div', { class: 'note' }, 'Contents were not captured for this buffer.'));
    return;
  }
  const passesFor = (sid: number) => ctx.model.passes.filter((p) => Object.values(p.json.bufSnaps).includes(sid));
  for (const [k, s] of snaps.slice(0, 8))
  {
    const sid = Number(k);
    const ps = passesFor(sid);
    el.append(section(`Contents as seen by ${ps.length ? ps.map((p) => p.label).slice(0, 3).join(', ') + (ps.length > 3 ? '…' : '') : 'a pass'}`, () => later(loadBufferSnapshot(ctx, sid).then((data) =>
    {
      if (!data || !data.ranges.length) return h('span', { class: 'note' }, s.missing ?? 'not captured');
      return h('div', null, data.ranges.map((r) => rawViewer(data, r.offset, r.bytes.byteLength)));
    })), { key: 'o-bufdata' }));
  }
}

function shaderModuleView(ctx: Ctx, o: any, el: HTMLElement): void
{
  const users = Object.values(ctx.cap.objects).filter((p: any) =>
    (p.type === 'GPURenderPipeline' || p.type === 'GPUComputePipeline') &&
    [p.desc?.vertex?.module, p.desc?.fragment?.module, p.desc?.compute?.module].some((m: any) => refId(m) === o.id));
  el.append(kv([
    ['Lines', String((o.code ?? '').split('\n').length)],
    ['Messages', o.messages?.length ? `${o.messages.filter((m: any) => m.type === 'error').length} errors, ${o.messages.filter((m: any) => m.type === 'warning').length} warnings` : 'none'],
    ['Used by', users.length ? h('span', null, users.slice(0, 12).map((u: any) => h('span', { style: 'margin-right:8px' }, refLink(ctx, { $ref: u.id })))) : '']
  ]));
  el.append(h('div', { style: 'margin:8px 0' }, h('button', { class: 'btn small', on: { click: () => ctx.openShader([{ stage: 'module', module: o.id }], 0) } }, 'Open in shader viewer')));
  const code = codeView(o.code ?? '', { messages: o.messages });
  code.style.maxHeight = '60vh';
  el.append(code);
}

function deviceView(ctx: Ctx, o: any, el: HTMLElement): void
{
  const info = o.info ?? o.adapterInfo;
  if (info) el.append(section('Adapter info', () => ptree(ctx, info), { key: 'o-ainfo' }));
  if (o.adapter) el.append(kv([['Adapter', refLink(ctx, o.adapter)]]));
  el.append(section(`Features (${o.features?.length ?? 0})`, () => h('div', { class: 'feature-list' }, (o.features ?? []).map((f: string) => h('span', { class: 'chip' }, f))), { key: 'o-feat' }));
  el.append(section('Limits', () => limitsTable(o.limits), { key: 'o-limits', collapsed: true }));
  if (o.desc) el.append(section('Requested with', () => ptree(ctx, o.desc), { key: 'o-req', collapsed: true }));
}

export function limitsTable(limits: any): HTMLElement
{
  return h('table', { class: 'grid' }, Object.entries(limits ?? {}).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) =>
    h('tr', null, h('td', null, k), h('td', { class: 'mono' }, String(v)))));
}

function usedBy(ctx: Ctx, id: number, el: HTMLElement): void
{
  const nodes = ctx.model.draws.filter((n) =>
  {
    const st = n.cmd?.draw?.state;
    if (!st) return false;
    if (refId(st.pipeline) === id) return true;
    return st.bindGroups?.some((g: any) => refId(g.bindGroup) === id);
  });
  if (!nodes.length) return;
  el.append(section(`Used by ${nodes.length} draw${nodes.length === 1 ? '' : 's'}`, () => h('div', null, nodes.slice(0, 200).map((n) =>
    h('div', null, h('a', { href: '#', on: { click: (e: Event) => { e.preventDefault(); ctx.showTab('commands'); ctx.selectNode(n, true); } } }, `#${n.drawNo} ${n.label}`), n.pass ? h('span', { class: 'chip', style: 'margin-left:6px' }, n.pass.label) : null)
  )), { key: 'o-usedby' }));
}

export { attachmentsTable };
